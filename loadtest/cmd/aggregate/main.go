// Command aggregate reads the raw k6 summary files under loadtest/results and
// prints, for every variant directory holding run1.json..runN.json, the
// median and [min-max] of each metric across runs. It only reorganises
// numbers that k6 wrote; it never estimates anything.
//
// Derived values (clearly labelled):
//   - "<counter> per s (run)": count / testRunDurationMs of that run.
//   - "<counter> per s (stage)": count / stage_seconds from meta.json, for
//     sweep stages whose length is fixed (constant-vus duration).
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type metric struct {
	Type   string             `json:"type"`
	Values map[string]float64 `json:"values"`
}

type summary struct {
	State struct {
		TestRunDurationMs float64 `json:"testRunDurationMs"`
	} `json:"state"`
	Metrics map[string]metric `json:"metrics"`
}

type meta struct {
	Description  string  `json:"description"`
	StageSeconds float64 `json:"stage_seconds"`
}

var runFile = regexp.MustCompile(`^run(\d+)\.json$`)

// Metrics worth tabulating; anything else (k6 internals) is skipped.
var keep = regexp.MustCompile(`^(http_reqs|http_req_duration|http_req_failed|iterations|dropped_iterations|data_received|` +
	`book_201_duration|book_end_to_end_duration|book_attempts|st_[a-z0-9_]+|draw_[a-z0-9_]+)(\{(stage|ep):[^}]+\})?$`)

var trendKeys = []string{"med", "p(95)", "p(99)", "max"}

func main() {
	root := flag.String("results", "loadtest/results", "results directory")
	flag.Parse()

	var dirs []string
	_ = filepath.Walk(*root, func(p string, info os.FileInfo, err error) error {
		if err == nil && info.IsDir() {
			if m, _ := filepath.Glob(filepath.Join(p, "run*.json")); len(m) > 0 {
				dirs = append(dirs, p)
			}
		}
		return nil
	})
	sort.Strings(dirs)

	fmt.Println("# Aggregated k6 results (generated by loadtest/cmd/aggregate)")
	fmt.Println()
	fmt.Println("Each cell is `median [min – max]` across the runs listed. Local, single machine.")
	fmt.Println("A counter missing from a run's summary (k6 omits counters that never fired) is counted as 0.")
	for _, d := range dirs {
		emit(*root, d)
	}
}

func emit(root, dir string) {
	entries, _ := os.ReadDir(dir)
	var runs []summary
	var files []string
	for _, e := range entries {
		if runFile.MatchString(e.Name()) {
			b, err := os.ReadFile(filepath.Join(dir, e.Name()))
			if err != nil {
				continue
			}
			var s summary
			if json.Unmarshal(b, &s) != nil {
				continue
			}
			runs = append(runs, s)
			files = append(files, e.Name())
		}
	}
	var m meta
	if b, err := os.ReadFile(filepath.Join(dir, "meta.json")); err == nil {
		_ = json.Unmarshal(b, &m)
	}
	rel, _ := filepath.Rel(filepath.Dir(root), dir)

	fmt.Printf("\n## %s\n\n", rel)
	if m.Description != "" {
		fmt.Printf("%s\n\n", m.Description)
	}
	fmt.Printf("Runs: %s (n=%d)\n\n", strings.Join(files, ", "), len(runs))
	fmt.Println("| metric | value |")
	fmt.Println("|---|---|")

	row := func(label string, get func(s summary) (float64, bool)) {
		var xs []float64
		for _, s := range runs {
			if v, ok := get(s); ok {
				xs = append(xs, v)
			}
		}
		if len(xs) > 0 {
			fmt.Printf("| %s | %s |\n", label, stat(xs))
		}
	}

	row("test duration (s)", func(s summary) (float64, bool) { return s.State.TestRunDurationMs / 1000, true })

	names := map[string]bool{}
	for _, s := range runs {
		for n := range s.Metrics {
			if keep.MatchString(n) {
				names[n] = true
			}
		}
	}
	var sorted []string
	for n := range names {
		sorted = append(sorted, n)
	}
	sort.Strings(sorted)

	for _, n := range sorted {
		name := n
		typ := ""
		for _, s := range runs {
			if mm, ok := s.Metrics[name]; ok {
				typ = mm.Type
				break
			}
		}
		switch typ {
		case "counter":
			// k6 omits a counter that was never incremented, so absent = 0.
			row(name+" count", func(s summary) (float64, bool) { return s.Metrics[name].Values["count"], true })
			if strings.HasPrefix(name, "http_reqs") || strings.HasPrefix(name, "st_201") || strings.HasPrefix(name, "iterations") {
				if strings.Contains(name, "{stage:") && m.StageSeconds > 0 {
					row(name+" per s (stage)", func(s summary) (float64, bool) {
						return s.Metrics[name].Values["count"] / m.StageSeconds, true
					})
				} else if !strings.Contains(name, "{stage:") {
					row(name+" per s (run)", func(s summary) (float64, bool) {
						return s.Metrics[name].Values["count"] / (s.State.TestRunDurationMs / 1000), true
					})
				}
			}
		case "rate":
			row(name+" rate", func(s summary) (float64, bool) { v, ok := s.Metrics[name].Values["rate"]; return v, ok })
		case "trend":
			empty := true
			for _, s := range runs {
				if s.Metrics[name].Values["count"] > 0 {
					empty = false
				}
			}
			if empty {
				continue // forced (threshold-only) submetric with no samples
			}
			unit := " (ms)"
			if strings.HasPrefix(name, "book_attempts") {
				unit = ""
			}
			for _, k := range trendKeys {
				key := k
				row(fmt.Sprintf("%s %s%s", name, key, unit), func(s summary) (float64, bool) {
					v, ok := s.Metrics[name].Values[key]
					return v, ok
				})
			}
		}
	}
}

func stat(xs []float64) string {
	s := append([]float64(nil), xs...)
	sort.Float64s(s)
	var med float64
	if n := len(s); n%2 == 1 {
		med = s[n/2]
	} else {
		med = (s[n/2-1] + s[n/2]) / 2
	}
	return fmt.Sprintf("%s [%s – %s]", f(med), f(s[0]), f(s[len(s)-1]))
}

func f(x float64) string {
	switch {
	case x == float64(int64(x)):
		return fmt.Sprintf("%d", int64(x))
	case x >= 100:
		return fmt.Sprintf("%.0f", x)
	case x >= 10:
		return fmt.Sprintf("%.1f", x)
	default:
		return fmt.Sprintf("%.2f", x)
	}
}
